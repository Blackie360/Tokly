// Clipboard watcher

/// Runs on the main thread. Returns what was copied if it should be remembered.
fn capture(app: &AppHandle) -> Option<(Vec<Raw>, Option<String>)> {
    let state = app.state::<AppState>();
    let count = platform::change_count();
    if state.change_count.swap(count, Ordering::SeqCst) == count {
        return None;
    }

    let settings = {
        let mut settings = state.settings.lock().unwrap();
        if settings.ignore_events {
            return None;
        }
        if settings.ignore_only_next_event {
            settings.ignore_only_next_event = false;
            settings.save(&state.settings_path);
            return None;
        }
        settings.clone()
    };

    let types = platform::pasteboard_types();
    if types
        .iter()
        .any(|t| TRANSIENT_TYPES.contains(&t.as_str()) || settings.ignored_pasteboard_types.contains(t))
    {
        return None;
    }

    let front = platform::frontmost();
    let listed = front.as_ref().is_some_and(|app| {
        settings.ignored_apps.iter().any(|entry| {
            app.bundle_id.as_deref() == Some(entry.as_str()) || app.name.as_deref() == Some(entry.as_str())
        })
    });
    if settings.ignore_all_apps_except_listed != listed {
        return None;
    }

    let contents = platform::read(|kind, siblings| {
        let has_file = siblings.iter().any(|t| t == FILE_URL);
        match kind {
            FILE_URL => settings.save_files,
            // Files carry their icon as an image, and a PNG makes the TIFF redundant.
            PNG => settings.save_images && !has_file,
            TIFF => settings.save_images && !has_file && !siblings.iter().any(|t| t == PNG),
            STRING => settings.save_text && (!has_file || settings.save_files),
            RTF | HTML => settings.save_text && !has_file,
            _ => false,
        }
    });
    if contents.is_empty() {
        return None;
    }

    if let Some((_, data)) = contents.iter().find(|c| c.0 == STRING) {
        let text = String::from_utf8_lossy(data);
        if contents.len() == 1 && text.trim().is_empty() {
            return None;
        }
        for pattern in &settings.ignored_regexps {
            if regex::Regex::new(pattern).is_ok_and(|re| re.is_match(&text)) {
                return None;
            }
        }
    }
    Some((contents, front.and_then(|app| app.name)))
}

fn start_watcher(app: AppHandle) {
    std::thread::spawn(move || loop {
        let state = app.state::<AppState>();
        let interval = state.settings().clipboard_check_interval.clamp(0.1, 10.0);
        std::thread::sleep(Duration::from_secs_f64(interval));

        let (sender, receiver) = mpsc::channel();
        let handle = app.clone();
        if app.run_on_main_thread(move || { let _ = sender.send(capture(&handle)); }).is_err() {
            continue;
        }
        if let Ok(Some((contents, source))) = receiver.recv() {
            let limit = state.settings().history_size;
            let added = state.history.lock().unwrap().add(contents, source, limit, history::now());
            if added.is_some() {
                history_changed(&app);
            }
        }
    });
}

fn main() {
    tauri::Builder::default()
        .plugin(
            tauri_plugin_global_shortcut::Builder::new()
                .with_handler(|app, _shortcut, event| {
                    if event.state() == ShortcutState::Pressed {
                        toggle_popup(app, false);
                    }
                })
                .build(),
        )
        .plugin(tauri_plugin_autostart::init(tauri_plugin_autostart::MacosLauncher::LaunchAgent, None))
        .invoke_handler(tauri::generate_handler![
            list_items,
            thumbnail,
            select_item,
            delete_item,
            toggle_pin,
            clear_history,
            get_settings,
            set_settings,
            storage_size,
            hide_popup,
            open_settings,
            quit
        ])
        .setup(|app| {
            app.set_activation_policy(tauri::ActivationPolicy::Accessory);

            let settings_path = app.path().app_config_dir()?.join("settings.json");
            let settings = Settings::load(&settings_path);
            let history = History::load(&app.path().app_data_dir()?.join("history"));
            let hotkey = settings.hotkey.clone();
            app.manage(AppState {
                history: Mutex::new(history),
                settings: Mutex::new(settings),
                settings_path,
                change_count: AtomicIsize::new(platform::change_count()),
                previous_app: AtomicI32::new(0),
                tray_position: Mutex::new(None),
                pause_item: Mutex::new(None),
            });

            let handle = app.handle().clone();
            build_tray(&handle)?;
            sync_tray(&handle);
            if let Err(error) = register_hotkey(&handle, &hotkey) {
                eprintln!("tokly: could not register {hotkey}: {error}");
            }

            if let Some(popup) = app.get_webview_window("popup") {
                let handle = handle.clone();
                popup.on_window_event(move |event| {
                    // TOKLY_KEEP_OPEN keeps the popup up after it loses focus, for inspecting it.
                    if let WindowEvent::Focused(false) = event {
                        if std::env::var_os("TOKLY_KEEP_OPEN").is_none() {
                            close_popup(&handle, false);
                        }
                    }
                });
            }
            // `Tokly --preferences` opens straight into the preferences window.
            if std::env::args().any(|argument| argument == "--preferences") {
                show_settings(&handle);
            }
            start_watcher(handle);
            Ok(())
        })
        .build(tauri::generate_context!())
        .expect("error while building Tokly")
        .run(|app, event| match event {
            // Closing the preferences window must not quit the menu bar app.
            tauri::RunEvent::ExitRequested { code: None, api, .. } => api.prevent_exit(),
            // Opening the app again while it runs (Finder, Spotlight, `open`) shows the history.
            tauri::RunEvent::Reopen { .. } => {
                let popup_open = app
                    .get_webview_window("popup")
                    .is_some_and(|window| window.is_visible().unwrap_or(false));
                if !popup_open {
                    toggle_popup(app, false);
                }
            }
            _ => {}
        });
}
