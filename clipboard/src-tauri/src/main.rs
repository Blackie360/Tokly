/// Copies carrying any of these are never recorded (nspasteboard.org conventions).
const TRANSIENT_TYPES: [&str; 3] = [
    "org.nspasteboard.TransientType",
    "org.nspasteboard.ConcealedType",
    "org.nspasteboard.AutoGeneratedType",
];

struct AppState {
    history: Mutex<History>,
    settings: Mutex<Settings>,
    settings_path: PathBuf,
    change_count: AtomicIsize,
    previous_app: AtomicI32,
    tray_position: Mutex<Option<(f64, f64)>>,
    pause_item: Mutex<Option<CheckMenuItem<Wry>>>,
}

impl AppState {
    fn settings(&self) -> Settings {
        self.settings.lock().unwrap().clone()
    }
}

#[derive(Serialize)]
#[serde(rename_all = "camelCase")]
struct Row {
    id: String,
    title: String,
    kind: String,
    pin: Option<String>,
    application: Option<String>,
    number_of_copies: u32,
    first_copied_at: f64,
    last_copied_at: f64,
    has_thumbnail: bool,
    width: Option<u32>,
    height: Option<u32>,
}

// ---------------------------------------------------------------------------
// Commands

#[tauri::command]
fn list_items(state: State<AppState>, query: String) -> Vec<Row> {
    let settings = state.settings();
    let history = state.history.lock().unwrap();
    let pinned = history::search(&query, history.pinned(), &settings.search_mode);
    let unpinned = history::search(&query, history.unpinned(&settings.sort_by), &settings.search_mode);
    let ordered = if settings.pin_to == "bottom" {
        unpinned.into_iter().chain(pinned)
    } else {
        pinned.into_iter().chain(unpinned)
    };
    ordered
        .map(|item| Row {
            id: item.id.clone(),
            title: item.title.chars().take(300).collect(),
            kind: item.kind.clone(),
            pin: item.pin.clone(),
            application: item.application.clone(),
            number_of_copies: item.number_of_copies,
            first_copied_at: item.first_copied_at,
            last_copied_at: item.last_copied_at,
            has_thumbnail: item.thumb.is_some(),
            width: item.width,
            height: item.height,
        })
        .collect()
}

#[tauri::command]
fn thumbnail(state: State<AppState>, id: String) -> Option<String> {
    let bytes = state.history.lock().unwrap().thumbnail(&id)?;
    Some(format!("data:image/png;base64,{}", base64::engine::general_purpose::STANDARD.encode(bytes)))
}

/// Puts an item back on the clipboard and optionally pastes it into the previous app.
#[tauri::command]
fn select_item(app: AppHandle, state: State<AppState>, id: String, paste: bool, plain: bool) {
    let mut contents = state.history.lock().unwrap().read_contents(&id);
    if contents.is_empty() {
        return;
    }
    if plain && contents.iter().any(|c| c.0 == STRING) {
        contents.retain(|c| c.0 == STRING);
    }
    state.change_count.store(platform::write(&contents), Ordering::SeqCst);
    state.history.lock().unwrap().touch(&id, history::now());
    close_popup(&app, true);
    history_changed(&app);

    if paste && platform::accessibility_trusted(true) {
        std::thread::spawn(|| {
            // Let the previous app become frontmost again before typing into it.
            std::thread::sleep(Duration::from_millis(180));
            platform::paste();
        });
    }
}

#[tauri::command]
fn delete_item(app: AppHandle, state: State<AppState>, id: String) {
    state.history.lock().unwrap().delete(&id);
    history_changed(&app);
}

#[tauri::command]
fn toggle_pin(app: AppHandle, state: State<AppState>, id: String) {
    let limit = state.settings().history_size;
    state.history.lock().unwrap().toggle_pin(&id, limit);
    history_changed(&app);
}

#[tauri::command]
fn clear_history(app: AppHandle, state: State<AppState>, all: bool) {
    state.history.lock().unwrap().clear(all);
    if state.settings().clear_system_clipboard {
        state.change_count.store(platform::clear(), Ordering::SeqCst);
    }
    history_changed(&app);
}

#[tauri::command]
fn get_settings(state: State<AppState>) -> Settings {
    state.settings()
}

#[tauri::command]
fn set_settings(app: AppHandle, state: State<AppState>, settings: Settings) -> Result<(), String> {
    let mut settings = settings;
    settings.history_size = settings.history_size.clamp(1, 999);
    settings.clipboard_check_interval = settings.clipboard_check_interval.clamp(0.1, 10.0);

    let previous = state.settings();
    let mut problem = None;
    if settings.hotkey != previous.hotkey {
        if let Err(error) = register_hotkey(&app, &settings.hotkey) {
            let _ = register_hotkey(&app, &previous.hotkey);
            problem = Some(format!("Could not use {}: {error}", settings.hotkey));
            settings.hotkey = previous.hotkey.clone();
        }
    }
    if settings.launch_at_login != previous.launch_at_login {
        let launcher = app.autolaunch();
        let result = if settings.launch_at_login { launcher.enable() } else { launcher.disable() };
        if let Err(error) = result {
            problem = Some(format!("Could not change launch at login: {error}"));
            settings.launch_at_login = previous.launch_at_login;
        }
    }

    settings.save(&state.settings_path);
    *state.settings.lock().unwrap() = settings.clone();
    {
        let mut history = state.history.lock().unwrap();
        history.trim(settings.history_size);
        history.save();
    }
    sync_tray(&app);
    let _ = app.emit("settings-changed", ());
    history_changed(&app);
    problem.map_or(Ok(()), Err)
}

#[tauri::command]
fn storage_size(state: State<AppState>) -> u64 {
    state.history.lock().unwrap().size_on_disk()
}

#[tauri::command]
fn hide_popup(app: AppHandle) {
    close_popup(&app, true);
}

#[tauri::command]
fn open_settings(app: AppHandle) {
    close_popup(&app, false);
    show_settings(&app);
}

#[tauri::command]
fn quit(app: AppHandle) {
    quit_app(&app);
}

// ---------------------------------------------------------------------------
// Windows

fn close_popup(app: &AppHandle, restore_focus: bool) {
    if let Some(window) = app.get_webview_window("popup") {
        let _ = window.hide();
    }
    if restore_focus {
        let pid = app.state::<AppState>().previous_app.swap(0, Ordering::SeqCst);
        if pid > 0 {
            platform::activate(pid);
        }
    }
}

fn toggle_popup(app: &AppHandle, from_tray: bool) {
    let Some(window) = app.get_webview_window("popup") else { return };
    if window.is_visible().unwrap_or(false) {
        close_popup(app, true);
        return;
    }
    let state = app.state::<AppState>();
    if let Some(front) = platform::frontmost() {
        if front.pid != std::process::id() as i32 {
            state.previous_app.store(front.pid, Ordering::SeqCst);
        }
    }

    let mode = state.settings().popup_position;
    let cursor = app.cursor_position().ok().map(|p| (p.x, p.y));
    let tray = *state.tray_position.lock().unwrap();
    let at_tray = from_tray || mode == "statusItem";
    let anchor = if at_tray { tray.or(cursor) } else { cursor };

    if !from_tray && mode == "center" {
        let _ = window.center();
    } else if !from_tray && mode == "lastPosition" {
        // Stays where it was left.
    } else if let Some((x, y)) = anchor {
        let size = window.outer_size().map(|s| (s.width as f64, s.height as f64)).unwrap_or((840.0, 1040.0));
        let (mut left, mut top) = if at_tray { (x - size.0 / 2.0, y) } else { (x, y) };
        // Both the pointer and monitor rectangles are in physical pixels.
        let monitors = app.available_monitors().unwrap_or_default();
        let containing = monitors.iter().find(|m| {
            let (origin, extent) = (m.position(), m.size());
            x >= origin.x as f64
                && x < origin.x as f64 + extent.width as f64
                && y >= origin.y as f64
                && y < origin.y as f64 + extent.height as f64
        });
        if let Some(monitor) = containing.or(monitors.first()) {
            let origin = monitor.position();
            let extent = monitor.size();
            let scale = monitor.scale_factor();
            let (min_x, min_y) = (origin.x as f64, origin.y as f64 + 26.0 * scale);
            let max_x = origin.x as f64 + extent.width as f64 - size.0;
            let max_y = origin.y as f64 + extent.height as f64 - size.1;
            if at_tray {
                top = min_y + 4.0 * scale;
            }
            left = left.min(max_x).max(min_x);
            top = top.min(max_y).max(min_y);
        }
        let _ = window.set_position(PhysicalPosition::new(left, top));
    }

    let _ = window.show();
    let _ = window.set_focus();
    let _ = window.emit("popup-shown", ());
}

fn show_settings(app: &AppHandle) {
    if let Some(window) = app.get_webview_window("settings") {
        let _ = window.show();
        let _ = window.set_focus();
        return;
    }
    let built = WebviewWindowBuilder::new(app, "settings", WebviewUrl::App("settings.html".into()))
        .title("Tokly Preferences")
        .inner_size(560.0, 560.0)
        .resizable(false)
        .build();
    if let Ok(window) = built {
        let _ = window.set_focus();
    }
}

fn quit_app(app: &AppHandle) {
    let state = app.state::<AppState>();
    let settings = state.settings();
    if settings.clear_on_quit {
        state.history.lock().unwrap().clear(false);
        if settings.clear_system_clipboard {
            platform::clear();
        }
    }
    app.exit(0);
}

// ---------------------------------------------------------------------------
// Tray and hotkey

fn history_changed(app: &AppHandle) {
    sync_tray(app);
    let _ = app.emit("history-changed", ());
}

/// Reflects pause state and the most recent copy in the menu bar.
fn sync_tray(app: &AppHandle) {
    let state = app.state::<AppState>();
    let settings = state.settings();
    if let Some(item) = state.pause_item.lock().unwrap().as_ref() {
        let _ = item.set_checked(settings.ignore_events);
    }
    let Some(tray) = app.tray_by_id("main") else { return };
    let mut title = String::new();
    if settings.ignore_events {
        title.push_str("paused");
    } else if settings.show_recent_copy_in_menu_bar {
        let history = state.history.lock().unwrap();
        if let Some(latest) = history.unpinned("lastCopiedAt").first() {
            let line: String = latest.title.split_whitespace().collect::<Vec<_>>().join(" ");
            let short: String = line.chars().take(24).collect();
            title = if line.chars().count() > 24 { format!("{short}…") } else { short };
        }
    }
    let _ = tray.set_title(if title.is_empty() { None } else { Some(title) });
}

fn update_settings(app: &AppHandle, change: impl FnOnce(&mut Settings)) {
    let state = app.state::<AppState>();
    {
        let mut settings = state.settings.lock().unwrap();
        change(&mut settings);
        settings.save(&state.settings_path);
    }
    sync_tray(app);
    let _ = app.emit("settings-changed", ());
}

fn register_hotkey(app: &AppHandle, hotkey: &str) -> Result<(), String> {
    let shortcuts = app.global_shortcut();
    let _ = shortcuts.unregister_all();
    if hotkey.is_empty() {
        return Ok(());
    }
    shortcuts.register(hotkey).map_err(|e| e.to_string())
}

fn build_tray(app: &AppHandle) -> tauri::Result<()> {
    let pause = CheckMenuItem::with_id(app, "pause", "Pause Capturing", true, false, None::<&str>)?;
    let skip = MenuItem::with_id(app, "skip", "Ignore Next Copy", true, None::<&str>)?;
    let open = MenuItem::with_id(app, "open", "Show History", true, None::<&str>)?;
    let preferences = MenuItem::with_id(app, "preferences", "Preferences…", true, Some("Cmd+,"))?;
    let quit = MenuItem::with_id(app, "quit", "Quit Tokly", true, Some("Cmd+Q"))?;
    let menu = Menu::with_items(
        app,
        &[
            &open,
            &PredefinedMenuItem::separator(app)?,
            &pause,
            &skip,
            &PredefinedMenuItem::separator(app)?,
            &preferences,
            &quit,
        ],
    )?;
    *app.state::<AppState>().pause_item.lock().unwrap() = Some(pause);

    let icon = tauri::image::Image::from_bytes(include_bytes!("../icons/tray.png"))?;
    TrayIconBuilder::with_id("main")
        .icon(icon)
        .icon_as_template(true)
        .tooltip("Tokly — clipboard history")
        .menu(&menu)
        .show_menu_on_left_click(false)
        .on_menu_event(|app, event| match event.id.as_ref() {
            "open" => toggle_popup(app, true),
            "pause" => update_settings(app, |s| s.ignore_events = !s.ignore_events),
            "skip" => update_settings(app, |s| s.ignore_only_next_event = true),
            "preferences" => show_settings(app),
            "quit" => quit_app(app),
            _ => {}
        })
        .on_tray_icon_event(|tray, event| {
            if let TrayIconEvent::Click {
                button: MouseButton::Left,
                button_state: MouseButtonState::Up,
                position,
                ..
            } = event
            {
                let app = tray.app_handle();
                *app.state::<AppState>().tray_position.lock().unwrap() = Some((position.x, position.y));
                // ⌥-click pauses capturing; ⌥⇧-click ignores only the next copy.
                match platform::held_modifiers() {
                    (true, true) => update_settings(app, |s| s.ignore_only_next_event = true),
                    (true, false) => update_settings(app, |s| s.ignore_events = !s.ignore_events),
                    _ => toggle_popup(app, true),
                }
            }
        })
        .build(app)?;
    Ok(())
}

